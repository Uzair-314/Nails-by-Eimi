/** Categories a product appears under, including parent rollups and the Deals shelf. */
export function categoriesFor(product) {
  const list = [product.category]
  if (product.category.includes('/')) list.push(product.category.split('/')[0])
  if (product.onSale || product.tags.includes('deal')) list.push('deals')
  return list
}
